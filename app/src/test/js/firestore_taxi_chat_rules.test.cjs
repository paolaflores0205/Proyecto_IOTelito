const assert=require('node:assert/strict');
const {call,fields,expect,write,commit,runAuthRules,countChecks}=require('./firestore_auth_rules.test.cjs');
async function seed(path,data){const r=await call('PATCH','/'+path,{fields:fields(data)},'owner');assert.ok(r.ok,await r.text());}
const message=(id,uid='client',role='CLIENT',text='Hola')=>write('taxiRequests/8001/messages/'+id,{senderUid:uid,senderRole:role,text},null,['createdAt']);
(async()=>{
 await runAuthRules();const start=countChecks();
 await seed('users/driver',{uid:'driver',role:'TAXISTA',active:true,name:'Conductor',email:'driver@example.test'});
 await seed('users/other-driver',{uid:'other-driver',role:'TAXISTA',active:true,name:'Otro',email:'other-driver@example.test'});
 await seed('taxistas/driver',{activo:true,disponible:true});
 await seed('taxistas/other-driver',{activo:true,disponible:true});
 const trip={id:8001,reserva:8001,clientUid:'client',taxistaUid:'',estado:'SOLICITADO'};
 await seed('taxiRequests/8001',trip);
 await expect(await commit([message('before')],'client'),false,'No escribe antes de asignación');
 await seed('taxiRequests/8001',{...trip,taxistaUid:'driver',estado:'ASIGNADO'});
 await expect(await commit([message('client')],'client'),true,'Cliente envía al conductor');
 await expect(await commit([message('driver','driver','TAXISTA')],'driver'),true,'Conductor asignado responde');
 await expect(await call('GET','/taxiRequests/8001/messages',undefined,'client'),true,'Cliente lee conversación');
 await expect(await call('GET','/taxiRequests/8001/messages',undefined,'driver'),true,'Conductor lee conversación');
 await expect(await call('GET','/taxiRequests/8001/messages',undefined,'other'),false,'Otro cliente no lee');
 await expect(await call('GET','/taxiRequests/8001/messages',undefined,'other-driver'),false,'Otro conductor no lee');
 await expect(await commit([message('spoof','driver','TAXISTA')],'client'),false,'No suplanta conductor');
 await expect(await commit([message('wrong-role','client','TAXISTA')],'client'),false,'No suplanta rol');
 await expect(await commit([message('empty','client','CLIENT','  ')],'client'),false,'No mensajes vacíos');
 await expect(await commit([message('long','client','CLIENT','x'.repeat(4001))],'client'),false,'Longitud acotada');
 await expect(await commit([write('taxiRequests/8001/messages/client',{text:'Editado'},['text'])],'client'),false,'Historial inmutable');
 await expect(await call('DELETE','/taxiRequests/8001/messages/client',undefined,'client'),false,'No borra mensajes');
 await seed('taxiRequests/8001',{...trip,taxistaUid:'driver',estado:'FINALIZADO'});
 await expect(await call('GET','/taxiRequests/8001/messages',undefined,'client'),true,'Conserva lectura al finalizar');
 await expect(await commit([message('closed')],'client'),false,'No envía después de finalizar');
 console.log(`Chat taxi: ${countChecks()-start} comprobaciones correctas, solo emulador.`);
})().catch(e=>{console.error(e);process.exitCode=1;});
